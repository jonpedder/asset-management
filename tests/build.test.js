import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

test("browser entry modules are syntactically valid", () => {
  for (const relative of ["../src/app.js", "../src/settings.js", "../src/map.js"]) execFileSync(process.execPath, ["--check", fileURLToPath(new URL(relative, import.meta.url))]);
});

test("runtime uses the required SDK loader and full-page OAuth redirect", async () => {
  const html = await readFile(new URL("../index.html", import.meta.url), "utf8");
  const auth = await readFile(new URL("../src/auth.js", import.meta.url), "utf8");
  const app = await readFile(new URL("../src/app.js", import.meta.url), "utf8");
  const map = await readFile(new URL("../src/map.js", import.meta.url), "utf8");
  const styles = await readFile(new URL("../styles/app.css", import.meta.url), "utf8");
  const config = JSON.parse(await readFile(new URL("../config/app.json", import.meta.url), "utf8"));
  assert.match(html, /<script type="module" src="https:\/\/js\.arcgis\.com\/5\.1\/"><\/script>/);
  assert.equal(config.oauth.clientId, "2eURPxapfMdaZiS7");
  assert.equal(config.oauth.mode, "redirect");
  assert.equal(config.oauth.redirectUrl, "https://jonpedder.github.io/asset-management/");
  assert.equal(config.oauth.popupCallbackUrl, "https://jonpedder.github.io/asset-management/oauth-callback.html");
  assert.match(auth, /popup:\s*!redirectMode/);
  assert.match(auth, /history\.replaceState/);
  assert.match(auth, /@arcgis\/core\/portal\/Portal\.js/);
  assert.match(auth, /getAuthenticatedUser/);
  assert.match(html, /id="sessionChip"[^>]*role="status"[^>]*hidden/);
  assert.match(html, /id="sessionUser">Not signed in<\/strong>/);
  assert.match(app, /Authenticated · \$\{username\}/);
  assert.match(app, /elements\.signInButton\.hidden = authenticated/);
  assert.match(map, /selectionReturnViewpoint = view\.viewpoint\.clone\(\)/); assert.match(map, /export async function restoreListView/); assert.match(map, /view\.goTo\(viewpoint/);
  assert.match(map, /function facilityResourceElement/); assert.match(map, /Available resources by type/); assert.match(map, /type: "custom"/);
  assert.match(map, /export async function captureResourceReportMap/); assert.match(map, /view\.takeScreenshot/); assert.match(map, /map\.remove\(reportLayer\)/);
  assert.equal(config.webMapItemId, "4cf195324bbb4c65b4defe7ae4b935bc");
  assert.equal(config.layers.resources, 0);
  assert.equal(config.layers.facilities, 1);
  assert.doesNotMatch(html, /Reported fleet benchmark/);
  assert.doesNotMatch(html, />Location validation</);
  assert.match(html, /id="bulkToggle"[^>]*aria-expanded="false"/);
  assert.match(html, /id="bulkContent"[^>]*hidden/);
  assert.ok(html.indexOf('id="bulkContent"') < html.indexOf('class="filters"'), "resource filters belong inside the collapsed bulk area");
  assert.ok(html.indexOf('class="filters"') < html.indexOf('id="bulkFacility"'), "filters appear before assignment controls");
  assert.match(html, /class="bulk-arrow"[^>]*aria-hidden="true">▶<\/span>/);
  assert.match(styles, /bulk-toggle\[aria-expanded="true"\] \.bulk-arrow\s*\{[^}]*rotate\(90deg\)/);
  assert.match(styles, /help-card summary::before\s*\{[^}]*content: "▶"/);
  assert.match(styles, /\.detail-actions\s*\{[^}]*align-items:\s*flex-start/);
  assert.match(styles, /\.detail-actions \.detail-edit-action\s*\{[^}]*margin-top:\s*0/);
  assert.match(styles, /\.sort-reset-button\s*\{[^}]*border:\s*1px solid var\(--app-accent\)[^}]*color:\s*var\(--app-accent\)/);
  assert.match(styles, /\.detail-panel\s*\{[^}]*position:\s*absolute[^}]*translateX\(100%\)/);
  assert.match(styles, /\.detail-panel\.open\s*\{[^}]*translateX\(0\)/);
  assert.match(styles, /tbody tr\.selected-row\s*\{[^}]*var\(--app-accent\)[^}]*0 0 10px/);
  assert.match(styles, /\.header-report-group\s*\{[^}]*display:\s*flex/);
  assert.match(styles, /\.resource-card-line\s*\{[^}]*justify-content:\s*space-between/); assert.match(styles, /\.resource-card-meta\s*\{[^}]*flex-wrap:\s*wrap/);
  assert.match(styles, /\.kpi-strip\s*\{[^}]*min-height:\s*60px/); assert.match(styles, /\.kpi-strip strong\s*\{[^}]*font-size:\s*1rem/); assert.match(styles, /\.workspace\s*\{[^}]*height:\s*calc\(100vh - 128px\)/);
});

