const ascii = (value) => String(value ?? "").normalize("NFKD").replace(/[\u0300-\u036f]/g, "").replace(/[\u2013\u2014]/g, "-").replace(/[\u2018\u2019]/g, "'").replace(/[\u201c\u201d]/g, '"').replace(/[^\x20-\x7e]/g, "?");
const escapePdf = (value) => ascii(value).replace(/([\\()])/g, "\\$1");
const validHex = (value, fallback) => /^#[0-9a-f]{6}$/i.test(value || "") ? value : fallback;
const rgb = (hex) => [1, 3, 5].map((index) => (parseInt(hex.slice(index, index + 2), 16) / 255).toFixed(3)).join(" ");
const command = (text, x, y, size, font, color) => `BT ${rgb(color)} rg /${font} ${size} Tf ${x} ${y} Td (${escapePdf(text)}) Tj ET`;

function wrap(value, width = 88) {
  const words = ascii(value).replace(/\s+/g, " ").trim().split(" ").filter(Boolean);
  const lines = []; let line = "";
  for (const word of words) {
    if (!line) line = word;
    else if (`${line} ${word}`.length <= width) line += ` ${word}`;
    else { lines.push(line); line = word; }
  }
  if (line) lines.push(line);
  return lines.length ? lines : [""];
}

function flatten(topics, generatedAt) {
  const rows = [{ kind: "title", text: "HELP & HOW-TO OPERATOR GUIDE" }, { kind: "meta", text: `Generated ${generatedAt.toLocaleString()}` }];
  topics.forEach((topic, index) => {
    rows.push({ kind: "topic", text: `${index + 1}. ${topic.title}` });
    for (const block of topic.blocks || []) {
      const prefix = block.kind === "list" ? (block.ordered ? `${block.number}. ` : "- ") : "";
      wrap(prefix + block.text, block.kind === "subheading" ? 78 : 90).forEach((text) => rows.push({ kind: block.kind, text }));
      if (["paragraph", "callout"].includes(block.kind)) rows.push({ kind: "space", text: "" });
    }
  });
  return rows;
}

function paginate(rows) {
  const pages = []; let page = []; let y = 655;
  for (const row of rows) {
    const gap = row.kind === "topic" ? 28 : row.kind === "title" ? 34 : row.kind === "space" ? 8 : 14;
    if ((row.kind === "topic" && y < 610) || y - gap < 54) { pages.push(page); page = []; y = 655; }
    page.push({ ...row, y }); y -= gap;
  }
  if (page.length) pages.push(page);
  return pages;
}

function pageStream(rows, pageNumber, pageCount, brand) {
  const colors = brand.colors;
  const commands = [
    `${rgb(colors.navy)} rg 0 704 612 88 re f`, `${rgb(colors.accent)} rg 0 698 612 6 re f`,
    command(brand.appName, 36, 758, 16, "F2", colors.text), command(brand.subtitle, 36, 738, 8, "F1", colors.muted),
    `${rgb(colors.panelAlt)} rg 0 0 612 32 re f`, command(`Generated by ${brand.appName}`, 36, 12, 7, "F1", colors.muted), command(`Page ${pageNumber} of ${pageCount}`, 520, 12, 7, "F1", colors.muted)
  ];
  for (const row of rows) {
    if (row.kind === "title") commands.push(`${rgb(colors.panelAlt)} rg 36 ${row.y - 10} 540 28 re f`, command(row.text, 44, row.y, 15, "F2", colors.text));
    else if (row.kind === "topic") commands.push(`${rgb(colors.accent)} rg 36 ${row.y - 9} 540 25 re f`, command(row.text, 44, row.y, 11, "F2", colors.background));
    else if (row.kind === "subheading") commands.push(command(row.text, 42, row.y, 10, "F2", colors.navy));
    else if (row.kind === "callout") commands.push(`${rgb(colors.accent)} rg 40 ${row.y - 9} 4 16 re f`, command(row.text, 50, row.y, 9, "F2", colors.navy));
    else if (row.kind !== "space") commands.push(command(row.text, row.kind === "list" ? 48 : 42, row.y, row.kind === "meta" ? 8 : 9, "F1", row.kind === "meta" ? colors.muted : colors.background));
  }
  return commands.join("\n");
}

export function buildHelpPdf(topics = [], generatedAt = new Date(), branding = {}) {
  const source = branding.colors || {};
  const brand = {
    appName: ascii(branding.appName || "Asset Management").slice(0, 80),
    subtitle: ascii(branding.subtitle || "Operational inventory preview").slice(0, 110),
    colors: {
      navy: validHex(source.navy, "#003b5c"), panelAlt: validHex(source.panelAlt, "#123247"), accent: validHex(source.accent, "#f2a900"),
      text: validHex(source.text, "#f4f7f9"), muted: validHex(source.muted, "#afc3cf"), background: validHex(source.background, "#071824")
    }
  };
  const pages = paginate(flatten(topics, generatedAt));
  const objects = [null, "<< /Type /Catalog /Pages 2 0 R >>", null, "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>", "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>"];
  const kids = [];
  pages.forEach((rows, index) => {
    const pageId = objects.length; const contentId = pageId + 1; kids.push(`${pageId} 0 R`);
    objects.push(`<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents ${contentId} 0 R >>`);
    const stream = pageStream(rows, index + 1, pages.length, brand);
    objects.push(`<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`);
  });
  objects[2] = `<< /Type /Pages /Kids [${kids.join(" ")}] /Count ${pages.length} >>`;
  let pdf = "%PDF-1.4\n"; const offsets = [0];
  for (let id = 1; id < objects.length; id += 1) { offsets[id] = pdf.length; pdf += `${id} 0 obj\n${objects[id]}\nendobj\n`; }
  const xref = pdf.length;
  pdf += `xref\n0 ${objects.length}\n0000000000 65535 f \n`;
  for (let id = 1; id < objects.length; id += 1) pdf += `${String(offsets[id]).padStart(10, "0")} 00000 n \n`;
  pdf += `trailer\n<< /Size ${objects.length} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF`;
  return new Blob([pdf], { type: "application/pdf" });
}
