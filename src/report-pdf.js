const text = (value) => String(value ?? "");
const ascii = (value) => text(value).normalize("NFKD").replace(/[\u0300-\u036f]/g, "").replace(/[\u2013\u2014]/g, "-").replace(/[\u2018\u2019]/g, "'").replace(/[\u201c\u201d]/g, '"').replace(/[^\x20-\x7E]/g, "?");
const escapePdf = (value) => ascii(value).replace(/([\\()])/g, "\\$1");
const validHex = (value, fallback) => /^#[0-9a-f]{6}$/i.test(value || "") ? value : fallback;
const rgb = (hex) => [1, 3, 5].map((index) => parseInt(hex.slice(index, index + 2), 16) / 255);
const color = (hex) => rgb(hex).map((value) => value.toFixed(3)).join(" ");

function wrap(value, width = 60) {
  const words = ascii(value).replace(/\s+/g, " ").trim().split(" ").filter(Boolean);
  if (!words.length) return [""];
  const lines = []; let line = "";
  for (const word of words) {
    if (!line) line = word;
    else if (`${line} ${word}`.length <= width) line += ` ${word}`;
    else { lines.push(line); line = word; }
  }
  if (line) lines.push(line);
  return lines;
}
function columnWidths(count) {
  if (count === 2) return [210, 330];
  if (count === 3) return [260, 140, 140];
  if (count === 4) return [190, 140, 110, 100];
  return [145, 110, 125, 70, 90];
}
function cellLimits(count) {
  if (count === 2) return [30, 48];
  if (count === 3) return [38, 20, 20];
  if (count === 4) return [27, 20, 16, 14];
  return [21, 16, 18, 10, 13];
}
function reportLines(report, generatedAt, hasMap) {
  const lines = [
    { kind: "title", text: report.title || "Inventory Report", size: 17, gap: 29 },
    { kind: "note", text: `Scope: ${report.scopeLabel || "Current list filters"}`, size: 9, gap: 15 },
    { kind: "note", text: `Generated: ${generatedAt.toLocaleString()}`, size: 9, gap: 19 },
    ...(hasMap ? [{ kind: "map", gap: 252 }] : [])
  ];
  for (const section of report.sections || []) {
    lines.push({ kind: "spacer", gap: 18 }, { kind: "section", text: section.title, size: 12, gap: 32 });
    const columns = section.columns || [];
    lines.push({ kind: "grid", cells: columns, header: true, size: columns.length >= 5 ? 7 : 9, gap: 20 });
    const limits = cellLimits(columns.length);
    for (const row of section.rows || []) {
      const wrapped = row.map((cell, index) => wrap(cell, limits[index] || 18));
      const lineCount = Math.max(1, ...wrapped.map((parts) => parts.length));
      for (let index = 0; index < lineCount; index += 1) {
        lines.push({ kind: "grid", cells: wrapped.map((parts) => parts[index] || ""), continuation: index > 0, size: columns.length >= 5 ? 7 : 8, gap: 17 });
      }
    }
    if (!(section.rows || []).length) lines.push({ kind: "note", text: "No records match the current report scope.", size: 9, gap: 16 });
  }
  return lines;
}
function paginate(lines) {
  const pages = []; let page = []; let y = 658;
  for (const line of lines) {
    const gap = line.gap || 14;
    if (y - gap < 52 && page.length) { pages.push(page); page = []; y = 658; }
    page.push({ ...line, y }); y -= gap;
  }
  if (page.length) pages.push(page);
  return pages;
}
function textCommand(value, x, y, size, font, fill) { return `BT ${color(fill)} rg /${font} ${size} Tf ${x} ${y} Td (${escapePdf(value)}) Tj ET`; }
function normalizeBranding(input = {}) {
  const source = input.colors || {};
  return {
    appName: ascii(input.appName || "Asset Management").slice(0, 60), subtitle: ascii(input.subtitle || "Operational inventory report").slice(0, 100), logo: input.logo, mapImage: input.mapImage,
    colors: { navy: validHex(source.navy, "#003B5C"), background: validHex(source.background, "#071824"), panelAlt: validHex(source.panelAlt, "#123247"), accent: validHex(source.accent, "#F2A900"), text: validHex(source.text, "#F4F7F9"), muted: validHex(source.muted, "#AFC3CF"), border: validHex(source.border, "#28495B") }
  };
}
function pageCommands(page, pageNumber, pageCount, branding, hasLogo, hasMap, reportTitle) {
  const colors = branding.colors;
  const commands = [
    `${color(colors.navy)} rg 0 700 612 92 re f`, `${color(colors.accent)} rg 0 695 612 5 re f`, `${color(colors.panelAlt)} rg 0 0 612 34 re f`,
    textCommand(branding.appName, 118, 758, 15, "F2", colors.text), textCommand(branding.subtitle, 118, 740, 8, "F1", colors.muted), textCommand(reportTitle, 118, 718, 10, "F2", colors.accent),
    textCommand(`Generated by ${branding.appName}`, 36, 13, 7, "F1", colors.muted), textCommand(`Page ${pageNumber} of ${pageCount}`, 520, 13, 7, "F1", colors.muted)
  ];
  if (hasLogo) {
    commands.push("1 1 1 rg 30 712 70 68 re f");
    const scale = Math.min(62 / branding.logo.width, 58 / branding.logo.height); const width = branding.logo.width * scale; const height = branding.logo.height * scale;
    commands.push(`q ${width.toFixed(2)} 0 0 ${height.toFixed(2)} ${(65 - width / 2).toFixed(2)} ${(746 - height / 2).toFixed(2)} cm /Logo Do Q`);
  } else {
    commands.push(`${color(colors.accent)} RG 2 w 34 716 56 56 re S`, textCommand("AM", 48, 738, 14, "F2", colors.accent));
  }
  for (const line of page) {
    if (line.kind === "title") {
      commands.push(`${color(colors.panelAlt)} rg 36 ${(line.y - 7).toFixed(2)} 540 24 re f`, textCommand(line.text, 44, line.y, line.size, "F2", colors.text));
    } else if (line.kind === "map" && hasMap) {
      commands.push(`${color(colors.border)} RG 1 w 36 ${(line.y - 226).toFixed(2)} 540 220 re S`, `q 540 0 0 220 36 ${(line.y - 226).toFixed(2)} cm /MapImage Do Q`);
    } else if (line.kind === "section") {
      commands.push(`${color(colors.accent)} rg 36 ${(line.y - 7).toFixed(2)} 540 21 re f`, textCommand(line.text.toUpperCase(), 44, line.y, line.size, "F2", colors.background));
    } else if (line.kind === "grid") {
      const widths = columnWidths(line.cells.length); let x = 36; const rowHeight = 17;
      if (line.header) commands.push(`${color(colors.panelAlt)} rg 36 ${(line.y - 7).toFixed(2)} 540 ${rowHeight} re f`);
      commands.push(`${color(colors.border)} RG .6 w 36 ${(line.y - 7).toFixed(2)} 540 ${rowHeight} re S`);
      line.cells.forEach((cell, index) => { if (index) commands.push(`${x} ${(line.y - 7).toFixed(2)} m ${x} ${(line.y + 10).toFixed(2)} l S`); commands.push(textCommand(cell, x + 4, line.y, line.size, line.header ? "F2" : "F1", line.header ? colors.text : colors.background)); x += widths[index]; });
    } else if (line.kind !== "spacer") commands.push(textCommand(line.text, 42, line.y, line.size || 9, "F1", line.kind === "note" ? colors.muted : colors.background));
  }
  return commands.join("\n");
}
function buildPdf(lines, brandingInput, reportTitle) {
  const branding = normalizeBranding(brandingInput); const pages = paginate(lines); const hasLogo = Boolean(branding.logo?.bytes?.length); const hasMap = Boolean(branding.mapImage?.bytes?.length);
  const objects = [null, "<< /Type /Catalog /Pages 2 0 R >>", null, "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>", "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>"]; let nextId = 5; let logoId = null; let mapId = null;
  const addImage = (image) => { const id = nextId++; const hex = [...image.bytes].map((byte) => byte.toString(16).padStart(2, "0")).join("").toUpperCase(); objects[id] = `<< /Type /XObject /Subtype /Image /Width ${image.width} /Height ${image.height} /ColorSpace /DeviceRGB /BitsPerComponent 8 /Filter [/ASCIIHexDecode /DCTDecode] /Length ${hex.length + 1} >>\nstream\n${hex}>\nendstream`; return id; };
  if (hasLogo) logoId = addImage(branding.logo); if (hasMap) mapId = addImage(branding.mapImage);
  const kids = [];
  pages.forEach((page, index) => { const pageId = nextId++; const contentId = nextId++; kids.push(`${pageId} 0 R`); const commands = pageCommands(page, index + 1, pages.length, branding, hasLogo, hasMap, reportTitle); const refs = [hasLogo && `/Logo ${logoId} 0 R`, hasMap && `/MapImage ${mapId} 0 R`].filter(Boolean).join(" "); objects[pageId] = `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 3 0 R /F2 4 0 R >>${refs ? ` /XObject << ${refs} >>` : ""} >> /Contents ${contentId} 0 R >>`; objects[contentId] = `<< /Length ${commands.length} >>\nstream\n${commands}\nendstream`; });
  objects[2] = `<< /Type /Pages /Kids [${kids.join(" ")}] /Count ${pages.length} >>`;
  let pdf = "%PDF-1.4\n"; const offsets = [0];
  for (let id = 1; id < objects.length; id += 1) { offsets[id] = pdf.length; pdf += `${id} 0 obj\n${objects[id]}\nendobj\n`; }
  const xref = pdf.length; pdf += `xref\n0 ${objects.length}\n0000000000 65535 f \n`; for (let id = 1; id < objects.length; id += 1) pdf += `${String(offsets[id]).padStart(10, "0")} 00000 n \n`;
  pdf += `trailer\n<< /Size ${objects.length} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF`;
  return new Blob([pdf], { type: "application/pdf" });
}
export function buildInventoryReportPdf(report = {}, generatedAt = new Date(), brandingInput = {}) {
  const hasMap = Boolean(brandingInput.mapImage?.bytes?.length);
  return buildPdf(reportLines(report, generatedAt, hasMap), brandingInput, ascii(report.title || "INVENTORY REPORT").toUpperCase());
}
export async function loadPdfImage(url) {
  if (!url || typeof document === "undefined") return null;
  const response = await fetch(url); if (!response.ok) throw new Error(`PDF image could not be loaded (${response.status}).`);
  const source = await response.blob(); let drawable; let objectUrl;
  try {
    objectUrl = URL.createObjectURL(source); const image = new Image(); image.decoding = "async"; image.src = objectUrl; await image.decode(); drawable = image;
    const scale = Math.min(1, 1200 / Math.max(drawable.naturalWidth, drawable.naturalHeight)); const canvas = document.createElement("canvas"); canvas.width = Math.max(1, Math.round(drawable.naturalWidth * scale)); canvas.height = Math.max(1, Math.round(drawable.naturalHeight * scale));
    const context = canvas.getContext("2d"); context.fillStyle = "#ffffff"; context.fillRect(0, 0, canvas.width, canvas.height); context.drawImage(drawable, 0, 0, canvas.width, canvas.height);
    const jpeg = await new Promise((resolve, reject) => canvas.toBlob((blob) => blob ? resolve(blob) : reject(new Error("PDF image conversion failed.")), "image/jpeg", .9));
    return { bytes: new Uint8Array(await jpeg.arrayBuffer()), width: canvas.width, height: canvas.height };
  } finally { if (objectUrl) URL.revokeObjectURL(objectUrl); }
}
